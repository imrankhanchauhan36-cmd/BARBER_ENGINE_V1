import express from "express";

import { protect }
  from "../middlewares/auth.middleware.js";

import { requireRole }
  from "../middlewares/role.middleware.js";

import {
  getNotifications,
  markAllRead,
  markOneRead,
  clearAllNotifications,
} from "../controllers/notification.controller.js";

const router = express.Router();

//////////////////////////////////////////////////////
// PROTECTED ROUTES
//////////////////////////////////////////////////////

router.use(protect);

//////////////////////////////////////////////////////
// OWNER + FIELD AGENT ACCESS
// FA-P2-A — widened from OWNER-only so a Field Agent can reuse this
// exact inbox (see controllers/notification.controller.js's
// resolveRecipient helper for the role-branch that keeps the OWNER
// path byte-for-byte unchanged).
//////////////////////////////////////////////////////

router.use(
  requireRole("OWNER", "FIELD_AGENT")
);

//////////////////////////////////////////////////////
// GET NOTIFICATIONS
//////////////////////////////////////////////////////

router.get(
  "/",
  getNotifications
);

//////////////////////////////////////////////////////
// MARK ALL READ
//////////////////////////////////////////////////////

router.patch(
  "/read-all",
  markAllRead
);

//////////////////////////////////////////////////////
// MARK SINGLE READ
//////////////////////////////////////////////////////

router.patch(
  "/:id/read",
  markOneRead
);

//////////////////////////////////////////////////////
// ARCHIVE ALL
//////////////////////////////////////////////////////

router.patch(
  "/archive-all",
  clearAllNotifications
);

//////////////////////////////////////////////////////
// EXPORT
//////////////////////////////////////////////////////

export default router;