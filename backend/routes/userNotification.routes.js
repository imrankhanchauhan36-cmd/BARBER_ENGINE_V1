import express from "express";

import { protect }
  from "../middlewares/auth.middleware.js";

import { requireRole }
  from "../middlewares/role.middleware.js";

import {
  deleteUserNotification,
  getUnreadNotificationCount,
  getUserNotifications,
  markAllUserNotificationsRead,
  markOneUserNotificationRead,
  clearAllUserNotifications,
} from "../controllers/userNotification.controller.js";

const router = express.Router();

//////////////////////////////////////////////////////
// PROTECTED ROUTES
//////////////////////////////////////////////////////

router.use(protect);

//////////////////////////////////////////////////////
// USER ACCESS
//////////////////////////////////////////////////////

router.use(
  requireRole("USER")
);

//////////////////////////////////////////////////////
// GET NOTIFICATIONS
//////////////////////////////////////////////////////

router.get(
  "/",
  getUserNotifications
);

//////////////////////////////////////////////////////
// GET UNREAD COUNT
//////////////////////////////////////////////////////

router.get(
  "/unread-count",
  getUnreadNotificationCount
);

//////////////////////////////////////////////////////
// MARK ALL READ
//////////////////////////////////////////////////////

router.patch(
  "/read-all",
  markAllUserNotificationsRead
);

//////////////////////////////////////////////////////
// MARK SINGLE READ
//////////////////////////////////////////////////////

router.patch(
  "/:id/read",
  markOneUserNotificationRead
);

//////////////////////////////////////////////////////
// ARCHIVE ALL
//////////////////////////////////////////////////////

router.patch(
  "/archive-all",
  clearAllUserNotifications
);

//////////////////////////////////////////////////////
// DELETE ONE (soft delete)
//////////////////////////////////////////////////////

router.delete(
  "/:id",
  deleteUserNotification
);

//////////////////////////////////////////////////////
// EXPORT
//////////////////////////////////////////////////////

export default router;
