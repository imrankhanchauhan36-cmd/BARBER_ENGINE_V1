import express from "express";

import { protect }
  from "../middlewares/auth.middleware.js";

import { requireRole }
  from "../middlewares/role.middleware.js";

import {
  getNotifications,
  markAllRead,
  markOneRead,
  clearAllNotifications,
} from "../controllers/notification.controller.js";

const router = express.Router();

//////////////////////////////////////////////////////
// PROTECTED ROUTES
//////////////////////////////////////////////////////

router.use(protect);

//////////////////////////////////////////////////////
// OWNER ACCESS
//////////////////////////////////////////////////////

router.use(
  requireRole("OWNER")
);

//////////////////////////////////////////////////////
// GET NOTIFICATIONS
//////////////////////////////////////////////////////

router.get(
  "/",
  getNotifications
);

//////////////////////////////////////////////////////
// MARK ALL READ
//////////////////////////////////////////////////////

router.patch(
  "/read-all",
  markAllRead
);

//////////////////////////////////////////////////////
// MARK SINGLE READ
//////////////////////////////////////////////////////

router.patch(
  "/:id/read",
  markOneRead
);

//////////////////////////////////////////////////////
// ARCHIVE ALL
//////////////////////////////////////////////////////

router.patch(
  "/archive-all",
  clearAllNotifications
);

//////////////////////////////////////////////////////
// EXPORT
//////////////////////////////////////////////////////

export default router;