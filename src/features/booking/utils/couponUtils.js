//////////////////////////////////////////////////////
// VALIDATE COUPON
//////////////////////////////////////////////////////

export const validateCoupon = ({
  coupon,

  subtotal,
}) => {

  //////////////////////////////////////////////////////
  // NO COUPON
  //////////////////////////////////////////////////////

  if (!coupon) {

    return {
      valid: false,

      message:
        "Coupon not found",
    };
  }

  //////////////////////////////////////////////////////
  // EXPIRED
  //////////////////////////////////////////////////////

  const now =
    new Date();

  const expiry =
    new Date(
      coupon.expiryDate
    );

  if (expiry < now) {

    return {
      valid: false,

      message:
        "Coupon expired",
    };
  }

  //////////////////////////////////////////////////////
  // MIN ORDER CHECK
  //////////////////////////////////////////////////////

  if (
    subtotal <
    (
      coupon.minOrder || 0
    )
  ) {

    return {
      valid: false,

      message:
        `Minimum order ₹${coupon.minOrder}`,
    };
  }

  //////////////////////////////////////////////////////
  // VALID
  //////////////////////////////////////////////////////

  return {
    valid: true,
  };
};

//////////////////////////////////////////////////////
// APPLY COUPON
//////////////////////////////////////////////////////

export const applyCoupon = ({
  coupon,

  subtotal,
}) => {

  //////////////////////////////////////////////////////
  // VALIDATE FIRST
  //////////////////////////////////////////////////////

  const validation =
    validateCoupon({
      coupon,
      subtotal,
    });

  if (!validation.valid) {

    return {
      success: false,

      discount: 0,

      message:
        validation.message,
    };
  }

  //////////////////////////////////////////////////////
  // FLAT DISCOUNT
  //////////////////////////////////////////////////////

  let discount = 0;

  if (
    coupon.type === "FLAT"
  ) {

    discount =
      coupon.value || 0;
  }

  //////////////////////////////////////////////////////
  // PERCENTAGE DISCOUNT
  //////////////////////////////////////////////////////

  if (
    coupon.type === "PERCENT"
  ) {

    discount =
      (
        subtotal *
        (
          coupon.value || 0
        )
      ) / 100;

    ////////////////////////////////////////////////////
    // MAX DISCOUNT LIMIT
    ////////////////////////////////////////////////////

    if (
      coupon.maxDiscount
    ) {

      discount =
        Math.min(
          discount,
          coupon.maxDiscount
        );
    }
  }

  //////////////////////////////////////////////////////
  // FINAL RESPONSE
  //////////////////////////////////////////////////////

  return {
    success: true,

    discount,

    finalAmount:
      Math.max(
        subtotal - discount,
        0
      ),
  };
};